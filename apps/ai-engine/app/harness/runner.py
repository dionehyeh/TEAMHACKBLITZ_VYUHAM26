"""Runner for orchestrating agent executions and streaming responses."""

import logging
from typing import Any, AsyncGenerator, Dict, List, Optional
from datetime import datetime, timezone
from pydantic import BaseModel

from pydantic_ai.messages import ModelRequest, ModelResponse, UserPromptPart, TextPart, ModelMessage

from app.harness.context import Citation, HarnessContext, ToolExecutionRecord
from app.harness.agents import default_agent, create_bizcontext_agent

logger = logging.getLogger(__name__)


class HarnessExecutionResult(BaseModel):
    """Result of a completed AI harness execution turn."""
    response: str
    citations: List[Citation]
    tool_calls: List[ToolExecutionRecord]
    conversation_id: str
    agent_id: Optional[str] = None
    usage: Optional[Dict[str, int]] = None
    created_at: str


def _convert_chat_history(history: Optional[List[Dict[str, str]]]) -> List[ModelMessage]:
    """Converts a generic chat history list into Pydantic AI ModelMessage objects."""
    if not history:
        return []
    
    messages: List[ModelMessage] = []
    for turn in history:
        role = turn.get("role", "user")
        content = turn.get("content", "")
        if not content:
            continue
        if role == "user":
            messages.append(ModelRequest(parts=[UserPromptPart(content=content)]))
        elif role == "assistant":
            messages.append(ModelResponse(parts=[TextPart(content=content)]))
    return messages


async def run_harness(
    prompt: str,
    context: HarnessContext,
    chat_history: Optional[List[Dict[str, str]]] = None,
    custom_system_prompt: Optional[str] = None,
) -> HarnessExecutionResult:
    """Executes a single conversational or operational turn against the Pydantic AI Harness."""
    logger.info(
        "Running harness for conv_id=%s org_id=%s user_id=%s prompt_len=%d",
        context.conversation_id,
        context.organisation_id,
        context.user_id,
        len(prompt),
    )

    agent = default_agent
    if custom_system_prompt:
        agent = create_bizcontext_agent(custom_system_prompt=custom_system_prompt)

    messages = _convert_chat_history(chat_history)

    try:
        run_result = await agent.run(
            prompt,
            deps=context,
            message_history=messages if messages else None,
        )

        response_text = str(run_result.output)

        usage_dict = None
        if hasattr(run_result, "usage") and run_result.usage:
            usage_dict = {
                "input_tokens": getattr(run_result.usage, "input_tokens", 0),
                "output_tokens": getattr(run_result.usage, "output_tokens", 0),
                "requests": getattr(run_result.usage, "requests", 1),
            }

        return HarnessExecutionResult(
            response=response_text,
            citations=context.collected_citations,
            tool_calls=context.recorded_tool_calls,
            conversation_id=context.conversation_id,
            agent_id=context.agent_id,
            usage=usage_dict,
            created_at=datetime.now(timezone.utc).isoformat(),
        )

    except Exception as exc:
        logger.error("Harness execution error: %s", exc, exc_info=True)
        return HarnessExecutionResult(
            response=f"Error executing request through AI harness: {str(exc)}",
            citations=context.collected_citations,
            tool_calls=context.recorded_tool_calls,
            conversation_id=context.conversation_id,
            agent_id=context.agent_id,
            created_at=datetime.now(timezone.utc).isoformat(),
        )


async def stream_harness(
    prompt: str,
    context: HarnessContext,
    chat_history: Optional[List[Dict[str, str]]] = None,
    custom_system_prompt: Optional[str] = None,
) -> AsyncGenerator[Dict[str, Any], None]:
    """Streams token chunks and lifecycle events (citations, tool calls) from the harness."""
    agent = default_agent
    if custom_system_prompt:
        agent = create_bizcontext_agent(custom_system_prompt=custom_system_prompt)

    messages = _convert_chat_history(chat_history)

    try:
        async with agent.run_stream(
            prompt,
            deps=context,
            message_history=messages if messages else None,
        ) as stream:
            # Stream text chunks as generated by Gemini
            async for chunk in stream.stream_text(delta=True):
                yield {
                    "event": "token",
                    "data": {"delta": chunk},
                }

            # Wait for stream to complete
            final_text = await stream.get_output()

            # Yield tool calls recorded during reasoning
            if context.recorded_tool_calls:
                yield {
                    "event": "tools",
                    "data": {"tool_calls": [t.model_dump() for t in context.recorded_tool_calls]},
                }

            # Yield citations discovered from Second Brain
            if context.collected_citations:
                yield {
                    "event": "citations",
                    "data": {"citations": [c.model_dump() for c in context.collected_citations]},
                }

            # Yield final completion summary
            yield {
                "event": "done",
                "data": {
                    "response": final_text,
                    "conversation_id": context.conversation_id,
                    "citations": [c.model_dump() for c in context.collected_citations],
                    "tool_calls": [t.model_dump() for t in context.recorded_tool_calls],
                },
            }

    except Exception as exc:
        logger.error("Error during streaming harness execution: %s", exc, exc_info=True)
        yield {
            "event": "error",
            "data": {"error": str(exc)},
        }
